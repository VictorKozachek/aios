#!/usr/bin/env python3
"""Convert a PNG into a Rust source file with a `&'static [u8]` bitmap.

The bare-metal kernel has no PNG decoder and no font rasteriser.  Design assets
are therefore baked at build time into plain byte arrays:

  * RGBA mode  - 4 bytes per pixel, straight (non-premultiplied) alpha,
                 rows top to bottom, no padding;
  * mask mode  - 1 byte per pixel, 8-bit coverage for a single ink colour
                 (used for the logo, the wordmark and the glyph atlas).

Mask mode is chosen automatically when every pixel has the same RGB value;
it is 4x smaller than RGBA and is what the kernel wants for text and
monochrome marks.  Blending in both modes is integer:

    dst = (dst * (255 - a) + tint * a) / 255

Usage
-----
    python3 tools/png2rust.py docs/design/assets/logo-aios.png \\
        --name logo_aios --out docs/design/generated/logo_aios.rs

    python3 tools/png2rust.py asset.png --mode rgba --print

Exit codes: 0 ok, 1 error, 2 --check mismatch.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image

BYTES_PER_LINE = 16


def rust_ident(name: str) -> str:
    ident = re.sub(r"[^0-9a-zA-Z_]+", "_", name).strip("_").lower()
    if not ident:
        raise ValueError("empty identifier")
    if ident[0].isdigit():
        ident = "_" + ident
    return ident


def load_rgba(path: Path) -> tuple[np.ndarray, str]:
    """Load a PNG as HxWx4 uint8, returning (pixels, original_mode)."""
    img = Image.open(path)
    mode = img.mode
    if img.format != "PNG":
        raise ValueError(f"{path}: expected PNG, got {img.format}")
    if mode not in ("RGBA", "RGB", "L", "LA", "P"):
        raise ValueError(f"{path}: unsupported PNG mode {mode!r}")
    rgba = np.asarray(img.convert("RGBA"), dtype=np.uint8)
    if rgba.ndim != 3 or rgba.shape[2] != 4:
        raise ValueError(f"{path}: cannot read as RGBA")
    return rgba, mode


def common_rgb(rgba: np.ndarray) -> tuple[int, int, int] | None:
    """Return the single RGB value if the whole image shares one, else None."""
    rgb = rgba[..., :3].reshape(-1, 3)
    first = rgb[0]
    if np.all(rgb == first):
        return int(first[0]), int(first[1]), int(first[2])
    return None


def emit_bytes(data: bytes, indent: str = "    ") -> str:
    lines = []
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i : i + BYTES_PER_LINE]
        lines.append(indent + ", ".join(str(b) for b in chunk) + ",")
    return "\n".join(lines)


def render_module(path: Path, name: str, mode: str) -> tuple[str, dict]:
    rgba, original_mode = load_rgba(path)
    h, w = rgba.shape[:2]
    ink = common_rgb(rgba)

    if mode == "auto":
        mode = "mask" if ink is not None else "rgba"
    if mode == "mask" and ink is None:
        raise ValueError(
            f"{path}: --mode mask requires a single ink colour, image has many"
        )
    if mode == "rgba" and rgba.shape[2] != 4:
        raise ValueError(f"{path}: RGBA expected")

    base = rust_ident(name)
    upper = base.upper()

    if mode == "mask":
        payload = rgba[..., 3].tobytes()
        kind = "alpha mask"
        ink_hex = "#%02X%02X%02X" % ink if ink else "#000000"
        doc = (
            f"/// 8-bit coverage mask, {w}x{h}, rows top to bottom.\n"
            f"/// Source ink: {ink_hex}; tint it at blit time:\n"
            f"///   dst = (dst * (255 - a) + tint * a) / 255\n"
        )
        array_name = f"{upper}_ALPHA"
    else:
        payload = rgba.tobytes()
        kind = "RGBA"
        doc = (
            f"/// Straight-alpha RGBA, {w}x{h}, rows top to bottom, 4 bytes/pixel.\n"
            f"///   dst = (dst * (255 - a) + src * a) / 255\n"
        )
        array_name = f"{upper}_RGBA"

    header = (
        f"// Generated by tools/png2rust.py from {path.as_posix()}\n"
        f"// Do not edit by hand - regenerate instead.\n"
        f"//\n"
        f"// {kind}, {w}x{h}, source PNG mode {original_mode!r}.\n\n"
    )
    body = (
        f"#[allow(dead_code)]\n"
        f"pub const {upper}_WIDTH: u32 = {w};\n"
        f"#[allow(dead_code)]\n"
        f"pub const {upper}_HEIGHT: u32 = {h};\n\n"
        f"{doc}"
        f"#[allow(dead_code)]\n"
        f"pub static {array_name}: &[u8] = &[\n"
        f"{emit_bytes(payload)}\n"
        f"];\n"
    )
    stats = {
        "width": w,
        "height": h,
        "mode": mode,
        "channels": 1 if mode == "mask" else 4,
        "bytes": len(payload),
        "text_bytes": len((header + body).encode()),
        "source_bytes": path.stat().st_size,
    }
    return header + body, stats


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("png", type=Path, help="input PNG")
    ap.add_argument("--name", help="Rust identifier base (default: file stem)")
    ap.add_argument(
        "--mode",
        choices=("auto", "mask", "rgba"),
        default="auto",
        help="auto (default) picks mask when the image has one ink colour",
    )
    ap.add_argument("--out", type=Path, help="output .rs file (default: stdout)")
    ap.add_argument("--check", action="store_true", help="verify --out is up to date")
    ap.add_argument("--print", dest="to_stdout", action="store_true", help="also print module")
    args = ap.parse_args(argv)

    if not args.png.is_file():
        print(f"error: {args.png}: no such file", file=sys.stderr)
        return 1
    name = args.name or args.png.stem
    try:
        module, st = render_module(args.png, name, args.mode)
    except Exception as exc:  # noqa: BLE001 - CLI boundary
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if not args.out or not args.out.is_file():
            print("error: --check needs an existing --out file", file=sys.stderr)
            return 1
        if args.out.read_text() != module:
            print(f"stale: {args.out}", file=sys.stderr)
            return 2
        print(f"ok: {args.out} up to date")
        return 0

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(module)
    if args.to_stdout or not args.out:
        sys.stdout.write(module)

    print(
        f"{args.png.name}: {st['width']}x{st['height']} {st['mode']} "
        f"{st['bytes']} bytes raw ({st['bytes'] / 1024:.1f} KiB), "
        f"PNG {st['source_bytes']} B, Rust text {st['text_bytes'] / 1024:.1f} KiB",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
